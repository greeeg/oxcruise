// Helpers shared by the generators in this folder.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

export const GENERATED = (recipe, source) =>
  `{/* generated by \`just ${recipe}\` from ${source}; do not edit */}\n`;

// Write a file and create its folder.
export function write(path, text) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

// MDX reads `{`, `}` and `<` in text as code. Escape them outside code spans and fences.
export function escapeMdx(markdown) {
  let fenced = false;
  return markdown
    .split("\n")
    .map((line) => {
      if (/^\s*```/.test(line)) {
        fenced = !fenced;
        return line;
      }
      if (fenced) return line;
      return line
        .split(/(`[^`]*`)/)
        .map((part, i) => (i % 2 ? part : part.replace(/[{}<]/g, (c) => `\\${c}`)))
        .join("");
    })
    .join("\n");
}

// A table cell: no pipes or line breaks.
export const cell = (text) => String(text).replaceAll("|", "\\|").replaceAll("\n", " ");

export const capitalize = (s) => s[0].toUpperCase() + s.slice(1);

// A YAML double-quoted string.
export const yaml = (s) => JSON.stringify(s);
