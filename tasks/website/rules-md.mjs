// Renders `oxcruise --rules` (JSON) as docs/rules.md. Usage: node rules-md.mjs rules.json > docs/rules.md
import { readFileSync } from "node:fs";

const rules = JSON.parse(readFileSync(process.argv[2], "utf8"));
const byCategory = Map.groupBy(rules, (r) => r.category);
const order = ["correctness", "suspicious", "style", "restriction", "nursery"];

let out = "<!-- generated by `just rule-docs` from the declare_rule! doc comments; do not edit -->\n\n# Built-in rules\n\n";
out += "| Rule | Category | Recommended |\n|---|---|---|\n";
for (const r of rules) out += `| [\`${r.name}\`](#${r.name}) | ${r.category} | ${r.recommended ? "yes" : ""} |\n`;
for (const cat of order.filter((c) => byCategory.has(c))) {
  out += `\n## ${cat[0].toUpperCase()}${cat.slice(1)}\n`;
  for (const r of byCategory.get(cat)) {
    out += `\n### ${r.name}\n\n_${r.recommended ? "In the \`oxcruise:recommended\` preset. " : ""}Since ${r.version}._\n\n${r.docs.replace(/^### /gm, "#### ")}\n`;
  }
}
process.stdout.write(out);
