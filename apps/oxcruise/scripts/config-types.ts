// Generates src-js/config.generated.ts from the JSON schema the Rust config crate emits.
//   just schema-json && just config-ts

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schema = JSON.parse(
  readFileSync(join(here, "../../../npm/oxcruise/configuration_schema.json"), "utf8"),
);
const compiled = await compile(schema, "OxcruiseConfig", {
  bannerComment: "// @generated by `just config-ts` from configuration_schema.json. Do not edit.\n",
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: false },
});
// The properties of the built-in rules are optional, so the index signature that types the
// plugin rules must accept `undefined` too.
const ts = compiled.replace(
  /(export interface Rules \{[\s\S]*?)\[k: string\]: RuleEntry;/,
  "$1[k: string]: RuleEntry | undefined;",
);
if (ts === compiled) throw new Error("the `Rules` interface has no RuleEntry index signature");
writeFileSync(join(here, "../src-js/config.generated.ts"), ts);
console.log("wrote src-js/config.generated.ts");
