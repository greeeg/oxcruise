use std::cell::RefCell;
use std::path::Path;

use bitflags::bitflags;
use oxcruise_core::{CycleStep, Edge, EdgeId, Graph, Module, ModuleId, Severity, Violation};
use oxcruise_graph::analyses::{Scc, distinct_dependents, strongly_connected};
use oxcruise_resolve::WorkspacePackage;

/// Clippy-style categories.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Category {
    /// Code that is almost certainly wrong.
    Correctness,
    /// Probably wrong or useless.
    Suspicious,
    Style,
    /// Forbids a feature or pattern; opt-in.
    Restriction,
    Nursery,
}

impl Category {
    pub fn as_str(self) -> &'static str {
        match self {
            Category::Correctness => "correctness",
            Category::Suspicious => "suspicious",
            Category::Style => "style",
            Category::Restriction => "restriction",
            Category::Nursery => "nursery",
        }
    }
}

/// Generated by [`declare_rule!`](oxcruise_macros::declare_rule).
pub trait RuleMeta {
    const NAME: &'static str;
    const CATEGORY: Category;
    const VERSION: &'static str;
    const RECOMMENDED: bool;
    const DOCS: &'static str;
    type Config;

    /// JSON schema of the options, only with the `ruledocs` feature.
    #[cfg(feature = "ruledocs")]
    fn config_schema() -> Option<serde_json::Value> {
        None
    }
}

bitflags! {
    /// Whole-graph analyses a rule needs. Only requested ones are computed.
    #[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
    pub struct Analyses: u8 {
        /// Strongly connected components over every edge.
        const CYCLES = 1;
        /// Strongly connected components without type-only edges.
        const CYCLES_RUNTIME = 1 << 1;
        /// Distinct dependent counts per module.
        const DEPENDENTS = 1 << 2;
    }
}

/// Results of the analyses some rule asked for.
#[derive(Default)]
pub struct AnalysisCache {
    pub scc_all: Option<Scc>,
    pub scc_runtime: Option<Scc>,
    pub dependents: Option<Vec<u32>>,
}

impl AnalysisCache {
    pub fn compute(graph: &Graph, wanted: Analyses) -> Self {
        // Independent analyses run in parallel.
        let (scc, (rt, dep)) = rayon::join(
            || {
                wanted
                    .contains(Analyses::CYCLES)
                    .then(|| strongly_connected(graph, &|_| true))
            },
            || {
                rayon::join(
                    || {
                        wanted
                            .contains(Analyses::CYCLES_RUNTIME)
                            .then(|| strongly_connected(graph, &|e: &Edge| !e.is_type_only()))
                    },
                    || {
                        wanted.contains(Analyses::DEPENDENTS).then(|| {
                            graph
                                .module_ids()
                                .map(|m| distinct_dependents(graph, m))
                                .collect::<Vec<_>>()
                        })
                    },
                )
            },
        );
        Self {
            scc_all: scc,
            scc_runtime: rt,
            dependents: dep,
        }
    }

    /// The SCC to use for cycle questions.
    pub fn scc(&self, ignore_type_only: bool) -> &Scc {
        let s = if ignore_type_only {
            &self.scc_runtime
        } else {
            &self.scc_all
        };
        s.as_ref()
            .expect("CYCLES analysis was not requested by any rule")
    }

    pub fn dependents_of(&self, m: ModuleId) -> u32 {
        self.dependents
            .as_ref()
            .expect("DEPENDENTS analysis was not requested by any rule")[m.idx()]
    }
}

/// Read-only state shared by every rule and thread of a run.
pub struct Shared<'a> {
    pub graph: &'a Graph,
    pub root: &'a Path,
    pub workspace: &'a [WorkspacePackage],
    pub analyses: &'a AnalysisCache,
}

/// Per-task context: shared state plus a private violation buffer, so rules
/// never contend on a lock while running under `par_iter`.
pub struct RuleCtx<'a> {
    pub shared: &'a Shared<'a>,
    pub rule: &'a str,
    pub severity: Severity,
    out: RefCell<Vec<Violation>>,
}

impl<'a> RuleCtx<'a> {
    pub fn new(shared: &'a Shared<'a>, rule: &'a str, severity: Severity) -> Self {
        Self {
            shared,
            rule,
            severity,
            out: RefCell::new(vec![]),
        }
    }

    pub fn graph(&self) -> &'a Graph {
        self.shared.graph
    }
    pub fn analyses(&self) -> &'a AnalysisCache {
        self.shared.analyses
    }
    pub fn module(&self, m: ModuleId) -> &'a Module {
        self.shared.graph.module(m)
    }
    pub fn edge(&self, e: EdgeId) -> &'a Edge {
        self.shared.graph.edge(e)
    }

    /// Violation on a whole module.
    pub fn report_module(&self, m: ModuleId, message: impl Into<String>) {
        self.out.borrow_mut().push(Violation::module(
            self.rule,
            self.severity,
            m,
            message.into(),
        ));
    }

    /// Violation on a dependency; carries its line and column.
    pub fn report_edge(&self, e: EdgeId, message: impl Into<String>) {
        self.report_edge_with_path(e, message, vec![]);
    }

    pub fn report_edge_with_path(
        &self,
        e: EdgeId,
        message: impl Into<String>,
        path: Vec<CycleStep>,
    ) {
        let edge = self.edge(e);
        self.out.borrow_mut().push(Violation {
            rule: self.rule.to_string(),
            severity: self.severity,
            from: edge.from,
            to: Some(edge.to),
            edge: Some(e),
            message: message.into(),
            loc: edge.loc,
            path,
        });
    }

    /// Push a fully built violation (for module-level findings that carry a target and path).
    pub fn push(&self, v: Violation) {
        self.out.borrow_mut().push(v);
    }

    pub fn into_violations(self) -> Vec<Violation> {
        self.out.into_inner()
    }
}

pub trait Rule: RuleMeta + Sized + Default + std::fmt::Debug + Send + Sync {
    /// Build the rule from its options (`null` when none were given).
    fn from_configuration(_value: serde_json::Value) -> Result<Self, String> {
        Ok(Self::default())
    }

    fn requirements(&self) -> Analyses {
        Analyses::empty()
    }

    fn check_module(&self, _m: ModuleId, _cx: &RuleCtx<'_>) {}
    fn check_edge(&self, _e: EdgeId, _cx: &RuleCtx<'_>) {}
    /// Whole-graph checks; runs once, on the calling thread.
    fn check_graph(&self, _cx: &RuleCtx<'_>) {}
}

/// Deserialize rule options with a clear error that names the rule.
pub fn parse_options<T: serde::de::DeserializeOwned + Default>(
    rule: &str,
    value: serde_json::Value,
) -> Result<T, String> {
    if value.is_null() {
        return Ok(T::default());
    }
    serde_json::from_value(value).map_err(|e| format!("invalid options for `{rule}`: {e}"))
}
